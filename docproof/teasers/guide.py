"""The two-page dos and don'ts that closes every author's teaser document.

House guidance for authors revising a teaser, distilled on 2026-09-20 from Reedsy,
Jane Friedman/IngramSpark and BookBub craft guidance, and edited for authors
on 2026-09-24. The author document carries no attribution paragraph. Page one is
about the story a teaser tells; page two is about the writing and revision."""

INTRODUCTION = ("Use these pages when you revise the option you choose. Each row pairs "
                "something that tends to work with a common way the same element goes wrong.")

STORY = [
    ("Opening hook",
     "Lead with the book’s distinctive premise or immediate pressure, so the reader has a concrete reason to continue.",
     "Begin with generic danger, vague destiny, or background before anything happens."),
    ("Protagonist",
     "Name the central character and what they want. Give only the background needed to understand that desire.",
     "List the cast, their biographies, or every viewpoint before establishing a central concern."),
    ("Disruption",
     "Show the event or obstacle that upsets the character’s situation and sets the story moving.",
     "Offer a string of unrelated incidents with no clear connection to the character’s goal."),
    ("Stakes",
     "Say what the character stands to lose, at the scale the book actually delivers.",
     "Rely on “everything is at stake,” or inflate a personal conflict into world-ending peril."),
    ("Story selection",
     "Choose the premise and a few compelling developments that make the reader want the experience.",
     "Compress the whole arc, the subplots, and the resolution into a miniature synopsis."),
    ("Spoilers",
     "Reveal enough setup to create curiosity; protect the discoveries that make reading worthwhile.",
     "Explain the solution, the ending, or a major reveal just to make the plot sound complete."),
    ("Setting and lore",
     "Include the context a reader needs to grasp the conflict. Make every unfamiliar term earn its place.",
     "Make readers decode a glossary, a family tree, or a history lesson before they understand the problem."),
    ("Tone and genre",
     "Let word choice and emphasis suggest the book’s real emotional experience and genre.",
     "Promise a light romance for a grim tragedy, or sell quiet fiction as a relentless thriller."),
    ("Accuracy",
     "Keep every claim about plot, relationships, motives, and abilities true to the book, even when simplifying.",
     "Invent a betrayal, a deadline, a power, a romance, or a choice because it makes the pitch sound stronger."),
    ("Closing line",
     "End on a specific tension left unresolved, as a question or a statement, whichever reads better.",
     "Force a rhetorical question, or assume a question automatically makes a stronger ending."),
]

CRAFT = [
    ("Length",
     "Treat 150–200 words as a starting range, and adjust to the genre and the space on your cover.",
     "Treat that range as a rule, or confuse 25–50-word promotional-email blurbs with back-cover copy."),
    ("Readability",
     "Use short, readable paragraphs with room around them in the actual cover layout.",
     "Pack text edge to edge, or shrink the type to rescue an overlong draft."),
    ("Verbs",
     "Favor active verbs and clear sentences that show what characters do and what threatens them.",
     "Let passive constructions or strings of adjectives carry the pitch."),
    ("Voice",
     "Choose a viewpoint and voice that suit the genre; compare effective blurbs for similar books.",
     "Assume third person is required. First-person copy can work well, in romance especially."),
    ("Comparisons",
     "Name a comparable book only when it helps readers picture the experience and genuinely fits.",
     "Borrow a famous title for prestige while promising an experience this book does not deliver."),
    ("Praise",
     "Use genuine, relevant endorsements when you have them; let the story stand alone when you don’t.",
     "Invent or inflate praise, awards, review counts, or bestseller status."),
    ("Drafts",
     "Try different hooks and emphases, ask readers which one pulls them in, then revise the strongest.",
     "Assume the first fluent draft is best, or mistake a few swapped words for a new approach."),
    ("Final edit",
     "Check clarity, flow, economy, and tone, and that character, conflict, and stakes are still clear.",
     "Keep an elegant sentence that adds confusion, repetition, or a promise the book doesn’t keep."),
]

